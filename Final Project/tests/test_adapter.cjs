const assert = require('node:assert/strict');
const { SensorAdapter } = require(process.argv[2] + '/sensors/sensorAdapter.js');
const ctx = {phase:'cooking',previewing:false,classifier:'WHISKING',microId:'whisk-batter'};
const adapter = new SensorAdapter();
adapter.hello({sessionId:'s',lastSeq:0,bridgeNow:1000,processRunning:true,source:'live',ready:null,latestState:null},1000);
let seq=0;
const send=(event,receivedAt=1000,now=1000)=>adapter.receive({sessionId:'s',receivedAt,event:{schema:'kitchen-motion.v1',seq:++seq,t:1,...event}},ctx,now);
const state=(hand,sensors={LH:true,RH:true,HF:true,HS:true})=>({type:'state',step:'auto',hand_state:hand,sensors,counts:{flip:0,twist_stroke:0,twist_cycle:0},features:null,timing:{},candidate:true});
assert.equal(send(state('twist')).length,0,'twist must not become stirring');
assert.equal(send(state('stir'))[0].signal,'active');
assert.equal(send({type:'sensor_fault',sensor:'RH',message:'lost'})[0].signal,'stopped');
assert.equal(send(state('stir',{LH:true,RH:false,HF:true})).length,0);
ctx.classifier='TWISTING';ctx.microId='add-salt';
send(state('idle'));
assert.equal(send({type:'hand_event',action:'twist_stroke',count:1,candidate:true},1000,5000).length,0,'old hand event rejected');
ctx.classifier='WHISKING';
assert.equal(send({type:'hand_event',action:'twist_stroke',count:2,candidate:true},5000,5000).length,0,'wrong step rejected');
assert.equal(send({type:'head_event',action:'confirm',duration:1,candidate:true},5000,5000)[0].kind,'confirm');
console.log('Adapter assertions passed');
