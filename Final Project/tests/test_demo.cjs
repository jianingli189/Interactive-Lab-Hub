const assert=require('node:assert/strict');
const root=process.argv[2];
const {SensorAdapter}=require(root+'/sensors/sensorAdapter.js');
const {parseMotionMessage}=require(root+'/sensors/protocol.js');
const {recipeReducer:r,initialRecipeState}=require(root+'/state/recipeState.js');
const a=new SensorAdapter();
a.hello({sessionId:'demo',lastSeq:0,bridgeNow:10000,processRunning:true,source:'live',ready:null,latestState:null},10000);
const context={phase:'cooking',previewing:false,classifier:'CHOPPING',microId:'chop-scallion'};
let seq=0;
const event=()=>({schema:'kitchen-motion.v1',seq:++seq,t:1,type:'state',step:'auto',hand_state:'moving',recognition_mode:'demo',candidate:true,sensors:{LH:true,RH:true,HF:true,HS:true},counts:{flip:0,twist_stroke:0,twist_cycle:0},features:null,timing:{}});
let e=event();assert.equal(parseMotionMessage(e).ok,true);assert.equal(parseMotionMessage({...e,recognition_mode:'classifier'}).ok,false);
let intents=a.receive({sessionId:'demo',receivedAt:10000,event:e},context,10000);
assert.equal(intents[0].classifier,'CHOPPING');
let s=r(initialRecipeState(),{type:'START_COOKING',now:10000});
const motion={type:'MOTION',classifier:'CHOPPING',signal:'active',intensity:.5,now:11000};
s=r(s,motion);assert.equal(s.micro['chop-scallion'].motion.activeSince,null,'tool gate remains closed');
s=r(s,{type:'TOOL_MANUAL',microId:'chop-scallion',stage:'using',now:12000});
s=r(s,{...motion,now:13000});assert.equal(s.micro['chop-scallion'].motion.activeSince,13000);
context.classifier='TWISTING';context.microId='add-salt';intents=a.receive({sessionId:'demo',receivedAt:14000,event:event()},context,14000);assert.equal(intents[0].classifier,'TWISTING');
e=event();e.sensors.RH=false;intents=a.receive({sessionId:'demo',receivedAt:15000,event:e},context,15000);assert.equal(intents[0].signal,'sample');
e=event();e.sensors.LH=false;e.sensors.RH=false;intents=a.receive({sessionId:'demo',receivedAt:16000,event:e},context,16000);assert.equal(intents[0].signal,'stopped');
console.log('PASS demo marker, step routing, tool gate, manual fallback, single hand continues, both hands invalid stop motion.');
